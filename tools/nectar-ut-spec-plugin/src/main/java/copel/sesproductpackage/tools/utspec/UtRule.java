package copel.sesproductpackage.tools.utspec;

/**
 * UT 仕様（Java_UT仕様 第3.6章「ツール」）の検査ルールの一覧。
 *
 * <p>違反の報告にはルール番号（{@link #code()}）と内容を出す。ルールの番号は仕様書の検査項目と対応させる。 検査の判定に使う具体的な語彙や文字数は {@link
 * UtSpecRules} に定義する。
 *
 * @author Copel Co., Ltd.
 */
public enum UtRule {

  /** 解析できないソースがある。 */
  UT00("UT-00", "UT のソースを構文解析できない"),
  /** 数えるコードを持つ本体クラスに対応するテストクラスがない。 */
  UT01("UT-01", "数えるコードを持つ本体クラスに対応するテストクラスがない（1対1）"),
  /** 対応する本体クラスがないテストクラスがある。 */
  UT02("UT-02", "対応する本体クラスがないテストクラス（1対1）"),
  /** テストファイルの配置と名前が規則に合わない。 */
  UT03("UT-03", "テストファイルは1ファイル1クラスで、ファイル名と同じ名前にし、本体名 + Test にする"),
  /** テストクラスの JavaDoc に対象クラスへの参照タグがない。 */
  UT04("UT-04", "テストクラスの JavaDoc に対象クラスを示す参照タグ（link）がない"),
  /** 第1階層の名前が本体に存在しない。 */
  UT05("UT-05", "第1階層の名前が対象メソッド・コンストラクタとして本体に存在しない"),
  /** 第2階層の種類が規定の5種類でない、または順番が違う。 */
  UT06("UT-06", "第2階層は正常系、異常系、境界値、認可、テナント隔離のいずれかを規定の順番で書く"),
  /** テストメソッドや @Nested の階層が規則に合わない。 */
  UT07("UT-07", "@Test と @ParameterizedTest は第2階層の @Nested クラスにだけ置く"),
  /** テスト名が {条件}の場合_{期待結果} の形になっていない。 */
  UT08("UT-08", "テスト名は {条件}の場合_{期待結果} の形にする"),
  /** 期待結果の語尾が許可された一覧にない。 */
  UT09("UT-09", "期待結果の語尾は許可された一覧（〜を返す など）から選ぶ"),
  /** JavaDoc の本文の文の数や文末が規則に合わない。 */
  UT10("UT-10", "JavaDoc の本文は2文にし、1文目は「ことを確かめる。」で終える（JavaDoc がない場合を含む）"),
  /** JavaDoc の本文2文目が枕詞で始まる。 */
  UT11("UT-11", "JavaDoc の本文2文目は枕詞（なぜ・理由・目的など）で始めず、「ため。」で終えない（理由は言い切り）"),
  /**
   * @given / @when / @then の数や中身が規則に合わない。
   */
  UT12("UT-12", "@given / @when / @then はそれぞれ1つだけ書き、空にせず、1文にする"),
  /** 1文が文字数の上限を超えている。 */
  UT13("UT-13", "1文は" + UtSpecRules.MAX_SENTENCE_LENGTH + "文字以内にする（タグの内容も対象）"),
  /** 禁止語を使っている。 */
  UT14("UT-14", "禁止語（正しく、正常に、適切に、など、うまく）を使わない"),
  /** 括弧を使っている。 */
  UT15("UT-15", "括弧（（）()【】［］[]「」『』）を使わない（{@link} と {@code} の中を除く）"),
  /** 絵文字または装飾記号を使っている。 */
  UT16("UT-16", "絵文字と装飾記号（※ → ★ ● など）を使わない"),
  /**
   * @DisplayName を使っている。
   */
  UT17("UT-17", "@DisplayName は使わない（テストのクラス名とメソッド名で表示名を示す）"),
  /** 除外（@CoverageExcludedGenerated）に理由（reason 属性の空でない文字列）がない。 */
  UT18("UT-18", "除外の理由を reason 属性の空でない文字列で書く");

  /** ルール番号（例: UT-01）。 */
  private final String code;

  /** ルールの内容。 */
  private final String description;

  /**
   * ルールを生成する。
   *
   * @param code ルール番号
   * @param description ルールの内容
   */
  UtRule(String code, String description) {
    this.code = code;
    this.description = description;
  }

  /**
   * ルール番号を返す。違反の報告に使うため、ルール番号は変えない。
   *
   * @return ルール番号（例: UT-01）
   */
  public String code() {
    return code;
  }

  /**
   * ルールの内容を返す。違反の一覧に付けて利用者が直すべき点を伝える。
   *
   * @return ルールの内容
   */
  public String description() {
    return description;
  }
}
